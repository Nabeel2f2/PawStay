    /** Search reservations by customer or pet name. A partial name is accepted. */
    private void searchReservations() {
        String query = search_Reserve.getText() == null ? "" : search_Reserve.getText().trim();

        if (query.isEmpty() || query.equalsIgnoreCase("Enter customer name")) {
            view_reserve();
            return;
        }

        String sql = "SELECT Reservation_ID, Customer, Pet, Arrival_Date, "
                   + "Departure_Date, Status, Estimated_Total "
                   + "FROM reservations "
                   + "WHERE LOWER(Customer) LIKE LOWER(?) "
                   + "OR LOWER(Pet) LIKE LOWER(?) "
                   + "ORDER BY Reservation_ID DESC";

        DefaultTableModel model = (DefaultTableModel) reservations.getModel();
        model.setRowCount(0);

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            String pattern = "%" + query + "%";
            pst.setString(1, pattern);
            pst.setString(2, pattern);

            try (ResultSet rs = pst.executeQuery()) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getInt("Reservation_ID"),
                        rs.getString("Customer"),
                        rs.getString("Pet"),
                        rs.getDate("Arrival_Date"),
                        rs.getDate("Departure_Date"),
                        rs.getString("Status"),
                        rs.getBigDecimal("Estimated_Total")
                    });
                }
            }

            if (model.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this,
                        "No reservation found for: " + query,
                        "Search", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "Reservation search failed: " + ex.getMessage(),
                    "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }

