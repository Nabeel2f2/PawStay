public void view_reserve() {

    try {
        Class.forName("com.mysql.cj.jdbc.Driver");

        java.sql.Connection con = java.sql.DriverManager.getConnection(
                "jdbc:mysql://localhost:3306/pet_care",
                "root",
                ""
        );

        String sql = "SELECT Reservation_ID, Customer, Pet, "
                + "Arrival_Date, Departure_Date, Status, Estimated_Total "
                + "FROM reservations";

        java.sql.Statement st = con.createStatement();
        java.sql.ResultSet rs = st.executeQuery(sql);

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) reservations.getModel();

        // Clear existing rows
        model.setRowCount(0);

        // Display database records in JTable
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("Reservation_ID"),
                rs.getString("Customer"),
                rs.getString("Pet"),
                rs.getDate("Arrival_Date"),
                rs.getDate("Departure_Date"),
                rs.getString("Status"),
                rs.getBigDecimal("Estimated_Total")
            });
        }

        rs.close();
        st.close();
        con.close();

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error loading reservations: " + e.getMessage()
        );
        e.printStackTrace();
    }
}
