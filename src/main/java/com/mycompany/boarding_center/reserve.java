    private void btn_bookingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_bookingActionPerformed
        // TODO add your handling code here:
      
    try {
        Connection con = DBConnection.getConnection();
        

        String customer = combo_Owner.getSelectedItem().toString();
        String pet = combo_Pet.getSelectedItem().toString();
        java.util.Date arrivalDate = arrival.getDate();
        java.util.Date departureDate = departure.getDate();
        String status = stats.getSelectedItem().toString();
        String total = estimated_total.getText();

        if (customer.equals("Select Customer") ||
            pet.equals("Select Pet Name") ||
            arrivalDate == null ||
            departureDate == null ||
            total.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please fill all required fields.");
            return;
        }

String sql = "INSERT INTO reservations "
                + "(Customer, Pet, Arrival_Date, Departure_Date, Status, Estimated_Total) "
                + "VALUES (?, ?, ?, ?, ?, ?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, customer);
        pst.setString(2, pet);
        pst.setDate(3, new java.sql.Date(arrivalDate.getTime()));
        pst.setDate(4, new java.sql.Date(departureDate.getTime()));
        pst.setString(5, status);
        pst.setBigDecimal(6, new java.math.BigDecimal(total));

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Booking confirmed successfully!");

        pst.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database Error: " + e.getMessage());
        e.printStackTrace();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid Estimated Total.");
    }

    }//GEN-LAST:event_btn_bookingActionPerformed



private void loadCustomerNames() {

    try {
        Connection con = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/pet_care",
            "root",
            ""
        );

        String sql = "SELECT Full_Name FROM customers";

        PreparedStatement pst = con.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        combo_Owner.removeAllItems();
        combo_Owner.addItem("Select Customer");

        while (rs.next()) {
            combo_Owner.addItem(rs.getString("Full_Name"));
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

