    /** Search pets by pet name or owner name. A partial name is accepted. */
    private void searchPets() {
        String query = search_Pets.getText() == null ? "" : search_Pets.getText().trim();

        if (query.isEmpty() || query.equalsIgnoreCase("Enter pet or owner name")) {
            view_pets();
            return;
        }

        String sql = "SELECT Pet_ID, Name, Owner, Species, Breed "
                   + "FROM pets_info "
                   + "WHERE LOWER(Name) LIKE LOWER(?) "
                   + "OR LOWER(Owner) LIKE LOWER(?) "
                   + "ORDER BY Name";

        DefaultTableModel model = (DefaultTableModel) tbl_Pets.getModel();
        model.setRowCount(0);

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            String pattern = "%" + query + "%";
            pst.setString(1, pattern);
            pst.setString(2, pattern);

            try (ResultSet rs = pst.executeQuery()) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getString("Pet_ID"),
                        rs.getString("Name"),
                        rs.getString("Owner"),
                        rs.getString("Species"),
                        rs.getString("Breed")
                    });
                }
            }

            if (model.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this,
                        "No pet or owner found for: " + query,
                        "Search", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "Pet search failed: " + ex.getMessage(),
                    "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }

