         public void view_Upcoming()
    {
                
try {
    Connection con = DBConnection.getConnection();

    String sql = "SELECT Date, Customer, Pet_Name, Breed, Kennel FROM upcoming";

    Statement st = con.createStatement();
    ResultSet rs = st.executeQuery(sql);

    DefaultTableModel model =
        (DefaultTableModel) Upcoming.getModel();

    // Clear existing rows
    model.setRowCount(0);

    // Add database records to the JTable
    while (rs.next()) {
        model.addRow(new Object[] {
            rs.getString("Date"),
            rs.getString("Customer"),
            rs.getString("Pet_Name"),
            rs.getString("Breed"),
            rs.getString("Kennel")
        });
    }

    rs.close();
    st.close();
   

} catch (Exception e) {
    e.printStackTrace();
}
    }
    
   
    

