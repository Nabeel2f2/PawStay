      private void createBarChart() {
    org.jfree.data.category.DefaultCategoryDataset dataset =
            new org.jfree.data.category.DefaultCategoryDataset();

    dataset.addValue(50, "Students", "January");
    dataset.addValue(75, "Students", "February");
    dataset.addValue(60, "Students", "March");
    dataset.addValue(90, "Students", "April");

    org.jfree.chart.JFreeChart chart =
            org.jfree.chart.ChartFactory.createBarChart(
                    "Monthly Students",
                    "Month",
                    "Number of Students",
                    dataset
            );

    org.jfree.chart.ChartPanel barChartPanel =
            new org.jfree.chart.ChartPanel(chart);

    chartPanel.setLayout(new java.awt.BorderLayout());
    chartPanel.add(barChartPanel, java.awt.BorderLayout.CENTER);
}
